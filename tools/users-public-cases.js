'use strict';
/**
 * What `listUsers()` discloses, for the Go port to reproduce exactly.
 *
 * ── A DENYLIST OF TWO, OVER A RECORD NOBODY FULLY MODELS ───────────────────
 *
 * `_toPublic` is `const { passwordHash, salt, ...pub } = user; return pub`. Two
 * fields removed, EVERYTHING ELSE KEPT — including fields no struct in this port
 * declares. A synthetic record here carries `allowedRouterIds`, `createdAt` and
 * a `note` that exists only to prove the point: all three survive.
 *
 * That makes the typed `store.User` the wrong tool for this endpoint. It models
 * five fields, so porting through it would DROP the other three and, worse, ADD
 * empty strings for fields a given record does not have — and the key set really
 * does differ per user, because the records differ.
 *
 * ── NOTHING HERE IS REAL ───────────────────────────────────────────────────
 *
 * The hashes are the literal words DEADBEEF and AAAA. No user, hash or salt from
 * the operator's /data is read: the live module is pointed at a throwaway
 * DATA_DIR this file writes.
 *
 *   node tools/users-public-cases.js            write the corpus
 *   node tools/users-public-cases.js --check    exit 1 if stale
 */

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const LIVE = path.resolve(process.env.MIKRODASH_SRC || path.join(__dirname, '..', '..', 'MikroDash'));
const OUT = path.join(__dirname, '..', 'testdata', 'users-public-cases.json');

const CASES = [
  ['a full record and a minimal one', [
    { id: 'u1', username: 'alice', passwordHash: 'DEADBEEF', salt: 'CAFE', role: 'admin',
      allowedRouterIds: ['r-A', 'r-B'], createdAt: 1700000000000,
      note: 'a field no struct in the port declares' },
    { id: 'u2', username: 'bob', passwordHash: 'AAAA', salt: 'BBBB', role: 'viewer' },
  ]],
  ['no users at all', []],
  // A record with NEITHER secret — the strip must not invent them, and must not
  // fail on their absence.
  ['a record carrying no hash or salt', [
    { id: 'u3', username: 'carol', role: 'viewer' },
  ]],
  // EMPTY IS NOT ABSENT. A field explicitly set to '' or null still survives the
  // spread; only the two named ones are removed.
  ['explicitly empty values', [
    { id: 'u4', username: '', passwordHash: '', salt: '', role: '',
      allowedRouterIds: [], createdAt: 0, nested: { a: 1 } },
  ]],
  ['a record that is only the two secrets', [
    { passwordHash: 'X', salt: 'Y' },
  ]],
];

function runCase(users) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'mdusers-'));
  try {
    fs.writeFileSync(path.join(dir, 'users.json'), JSON.stringify(users));
    const out = execFileSync(process.execPath, ['-e', `
      const U = require(${JSON.stringify(path.join(LIVE, 'src', 'users.js'))});
      U.listUsers().then(l => process.stdout.write(JSON.stringify(l)));
    `], { env: { ...process.env, DATA_DIR: dir }, encoding: 'utf8' });
    return JSON.parse(out);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

function main() {
  const check = process.argv.includes('--check');
  const cases = CASES.map(([note, users]) => ({ note, users, public: runCase(users) }));

  // A floor: if the strip ever stopped stripping, this corpus would record the
  // hashes and the Go test would then "agree" with a leak.
  const leaked = JSON.stringify(cases.map(c => c.public));
  for (const bad of ['DEADBEEF', 'CAFE', 'AAAA', 'BBBB']) {
    if (leaked.includes(bad)) {
      console.error('the live listUsers() returned a secret (' + bad + ') — refusing to ' +
                    'record a corpus that would make a leak look correct');
      process.exit(1);
    }
  }

  const body = JSON.stringify({
    note: 'Generated by tools/users-public-cases.js from the LIVE src/users.js. Do not edit. ' +
          'Every value is synthetic; no record from the operator /data is read.',
    stripped: ['passwordHash', 'salt'],
    cases,
  }, null, 2) + '\n';

  if (check) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
    if (cur !== body) {
      console.error('testdata/users-public-cases.json is stale — run: node tools/users-public-cases.js');
      process.exit(1);
    }
    console.log('user disclosure cases up to date (' + cases.length + ' cases)');
    return;
  }
  fs.writeFileSync(OUT, body);
  console.log('wrote ' + path.relative(path.join(__dirname, '..'), OUT) + ' — ' + cases.length + ' cases');
}

main();
