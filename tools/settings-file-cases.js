'use strict';
/**
 * The BYTES the live `save()` writes, for the Go writer to reproduce exactly.
 *
 * ── WHY BYTES AND NOT VALUES ───────────────────────────────────────────────
 *
 * Both apps read this file, so any writer that produces equivalent JSON is
 * functionally fine. The reason to go further is the operator: settings.json is
 * a file people diff, hand-edit and copy between installs, and two writers that
 * disagree about key order or escaping turn the first save after cutover into a
 * 113-line diff that means nothing. Go's encoding/json sorts keys and escapes
 * `<` as `<`; JavaScript does neither.
 *
 * ── THE CREDENTIAL LINES ARE NORMALISED, AND THAT IS NOT A LOOPHOLE ────────
 *
 * AES-GCM seals with a random IV, so the ciphertext differs on every run and a
 * byte comparison of those lines could only ever fail. They are replaced by a
 * placeholder on BOTH sides, and their presence and non-emptiness is still
 * checked — what remains compared byte-for-byte is the other ~107 keys, which is
 * where order, indentation, escaping and number formatting live.
 *
 *   node tools/settings-file-cases.js            write the corpus
 *   node tools/settings-file-cases.js --check    exit 1 if stale
 */

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const LIVE = path.resolve(process.env.MIKRODASH_SRC || path.join(__dirname, '..', '..', 'MikroDash'));
const OUT = path.join(__dirname, '..', 'testdata', 'settings-file-cases.json');
const ENCRYPTED = ['routerPass', 'telegramBotToken', 'pushbulletApiKey',
                   'smtpUser', 'smtpPass', 'ntfyToken'];

const CASES = [
  ['defaults only', {}],
  ['a handful of ordinary changes', {
    topN: 25, pingTarget: '198.51.100.9', pingEnabled: false, displayTimezone: 'Europe/Berlin',
  }],
  // ESCAPING. A notification template is free text and routinely contains a tag
  // or a quote; Go would write < where Node writes < unless told not to.
  ['a template with characters Go escapes by default', {
    notifTitle: 'Alert <b>{{router}}</b> & "quoted"',
    notifBody: "line1\nline2\ttab <script>alert('x')</script> © é 😀",
  }],
  ['every credential set', {
    routerPass: 'NOT-A-REAL-PASSWORD', telegramBotToken: 'NOT-A-REAL-TOKEN',
    smtpPass: 'NOT-A-REAL-SMTP-PASS',
  }],
  ['numbers at their edges', { pollConns: 1000, maxConns: 100000, alertCpuThreshold: 1 }],
];

function runCase(updates) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'mdfile-'));
  try {
    execFileSync(process.execPath, ['-e', `
      const S = require(${JSON.stringify(path.join(LIVE, 'src', 'settings.js'))});
      S.save(JSON.parse(${JSON.stringify(JSON.stringify(updates))}));
    `], { env: { ...process.env, DATA_DIR: dir }, encoding: 'utf8' });
    const raw = fs.readFileSync(path.join(dir, 'settings.json'), 'utf8');
    return normalise(raw);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

/** Replace each credential's ciphertext with a marker, keeping set/unset. */
function normalise(text) {
  const obj = JSON.parse(text);
  let out = text;
  for (const f of ENCRYPTED) {
    const v = obj[f];
    if (typeof v !== 'string') continue;
    out = out.replace(JSON.stringify(f) + ': ' + JSON.stringify(v),
                      JSON.stringify(f) + ': ' + JSON.stringify(v ? '<SEALED>' : ''));
  }
  return out;
}

function main() {
  const check = process.argv.includes('--check');
  const cases = CASES.map(([note, updates]) => ({ note, updates, file: runCase(updates) }));

  const body = JSON.stringify({
    note: 'Generated by tools/settings-file-cases.js — the exact bytes the live save() writes, ' +
          'with each credential ciphertext replaced by <SEALED> because AES-GCM uses a random IV.',
    sealedMarker: '<SEALED>',
    encrypted: ENCRYPTED,
    cases,
  }, null, 2) + '\n';

  if (check) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
    if (cur !== body) {
      console.error('testdata/settings-file-cases.json is stale — run: node tools/settings-file-cases.js');
      process.exit(1);
    }
    console.log('settings file cases up to date (' + cases.length + ' cases)');
    return;
  }
  fs.writeFileSync(OUT, body);
  console.log('wrote ' + path.relative(path.join(__dirname, '..'), OUT) + ' — ' + cases.length +
              ' cases, ' + cases[0].file.split('\n').length + ' lines each');
}

main();
